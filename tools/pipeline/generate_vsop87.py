#!/usr/bin/env python3
"""
Content pipeline for Transparent Earth: the planetary theory.

Writes packages/core/src/astro/vsop87-data.ts: the VSOP87B series
(Bretagnon & Francou 1988, A&A 202, 309; CDS VI/81) for Mercury to
Neptune, cut down to the terms that matter at the app's accuracy.

VSOP87B gives heliocentric longitude L, latitude B (radians) and radius R
(au) in the dynamical ecliptic and equinox of J2000 as sums of
A·cos(B + C·t)·t^n, t in Julian millennia (TDB) from J2000. The full
theory has 1,000-7,000 terms per planet and is good to 1 arcsecond over
millennia. Dropping every term whose amplitude over the SPAN_MILLENNIA
window stays below the planet's cut keeps the truncation error - measured
here against the full series, as an angle seen from the nearest the planet
comes to the Earth - within TARGET_ARCSEC for 1800-2200.

Usage:
    python3 tools/pipeline/generate_vsop87.py

Raw downloads are cached in tools/pipeline/.cache/. Needs numpy.
"""

import math
from pathlib import Path

import numpy as np

from fetch_cache import cached_fetch

# The CDS original and its CfA mirror serve the same catalogue.
VSOP_URLS = [
    "https://vizier.cfa.harvard.edu/ftp/cats/VI/81/VSOP87B.{ext}",
    "https://cdsarc.cds.unistra.fr/ftp/cats/VI/81/VSOP87B.{ext}",
    "https://ftp.imcce.fr/pub/ephem/planets/vsop87/VSOP87B.{ext}",
]

# name, file extension, nearest approach to the Earth in au (1 au for the Earth: it stands for the Sun's place).
PLANETS = [
    ("mercury", "mer", 0.53),
    ("venus", "ven", 0.26),
    ("earth", "ear", 0.26),
    ("mars", "mar", 0.37),
    ("jupiter", "jup", 3.9),
    ("saturn", "sat", 8.0),
    ("uranus", "ura", 17.2),
    ("neptune", "nep", 28.8),
]

# The series are cut for |t| <= this (1800-2200).
SPAN_MILLENNIA = 0.2
# Truncation error allowed, as seen from the Earth.
TARGET_ARCSEC = 0.5

REPO_ROOT = Path(__file__).resolve().parents[2]
OUTPUT = REPO_ROOT / "packages" / "core" / "src" / "astro" / "vsop87-data.ts"

Series = dict[int, dict[int, list[tuple[float, float, float]]]]


def parse_vsop(text: str) -> Series:
    """{variable 1..3: {power: [(A, B, C), ...]}} from one VSOP87B file."""
    series: Series = {1: {}, 2: {}, 3: {}}
    variable = power = -1
    for line in text.splitlines():
        if line.startswith(" VSOP87"):
            variable = int(line[41])
            power = int(line[59])
            series[variable][power] = []
            continue
        if len(line) < 131:
            continue
        # Fixed columns: (1x,i4,i5,12i3,f15.11,2f18.11,f14.11,f20.11); the last three are A, B, C.
        series[variable][power].append((float(line[79:97]), float(line[97:111]), float(line[111:131])))
    return series


def evaluate(series: Series, t: np.ndarray) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    out = []
    for variable in (1, 2, 3):
        total = np.zeros_like(t)
        for power, terms in series[variable].items():
            if not terms:
                continue
            a = np.array(terms)
            total += (a[:, 0, None] * np.cos(a[:, 1, None] + a[:, 2, None] * t[None, :])).sum(axis=0) * t**power
        out.append(total)
    return out[0], out[1], out[2]


def to_xyz(lon: np.ndarray, lat: np.ndarray, radius: np.ndarray) -> np.ndarray:
    return np.stack([radius * np.cos(lat) * np.cos(lon), radius * np.cos(lat) * np.sin(lon), radius * np.sin(lat)])


def truncate(series: Series, cut: float) -> Series:
    """Keep terms whose amplitude times t^n reaches `cut` (radians; au for R, scaled by the caller) in the window."""
    kept: Series = {1: {}, 2: {}, 3: {}}
    for variable in (1, 2, 3):
        for power, terms in series[variable].items():
            limit = cut / (SPAN_MILLENNIA**power)
            rows = [term for term in terms if abs(term[0]) >= limit]
            if rows:
                kept[variable][power] = rows
    return kept


def truncation_error_arcsec(full: Series, cut_series: Series, nearest_au: float) -> float:
    t = np.linspace(-SPAN_MILLENNIA, SPAN_MILLENNIA, 4001)
    delta = to_xyz(*evaluate(full, t)) - to_xyz(*evaluate(cut_series, t))
    return float(np.degrees(np.sqrt((delta**2).sum(axis=0)).max() / nearest_au) * 3600)


def fit_cut(full: Series, nearest_au: float) -> tuple[Series, float, float]:
    """The largest cut (fewest terms) on a ×0.7 ladder that meets the target."""
    cut = 1e-5
    while True:
        cut_series = truncate(full, cut)
        error = truncation_error_arcsec(full, cut_series, nearest_au)
        if error <= TARGET_ARCSEC:
            return cut_series, cut, error
        cut *= 0.7


def number(value: float) -> str:
    text = repr(value)
    return text[:-2] if text.endswith(".0") else text


def main() -> None:
    lines = [
        "/**",
        " * VSOP87B planetary series, truncated. GENERATED by tools/pipeline/generate_vsop87.py",
        " * from CDS VI/81 (Bretagnon & Francou 1988) - do not edit.",
        " *",
        " * Per planet: l, b (radians) and r (au), heliocentric, dynamical ecliptic and",
        " * equinox J2000. Each is a list over the power n of t (Julian millennia from",
        " * J2000) of flat triples A, B, C: the sum of A·cos(B + C·t), times t^n.",
        f" * Truncation error within {TARGET_ARCSEC} arcsecond as seen from the Earth, 1800-2200.",
        " */",
        "",
        "export interface Vsop87Series {",
        "  readonly l: readonly (readonly number[])[];",
        "  readonly b: readonly (readonly number[])[];",
        "  readonly r: readonly (readonly number[])[];",
        "}",
        "",
        "export type Vsop87Planet = " + " | ".join(f"'{name}'" for name, _, _ in PLANETS) + ";",
        "",
        "export const VSOP87: Readonly<Record<Vsop87Planet, Vsop87Series>> = {",
    ]
    for name, ext, nearest_au in PLANETS:
        path = cached_fetch([url.format(ext=ext) for url in VSOP_URLS], f"VSOP87B.{ext}")
        full = parse_vsop(path.read_text())
        cut_series, cut, error = fit_cut(full, nearest_au)
        count = sum(len(rows) for powers in cut_series.values() for rows in powers.values())
        total = sum(len(rows) for powers in full.values() for rows in powers.values())
        print(f"{name:8s} cut {cut:.2e}  {count:4d} of {total:4d} terms  truncation {error:.3f} arcsec")
        lines.append(f"  {name}: {{")
        for variable, key in ((1, "l"), (2, "b"), (3, "r")):
            powers = cut_series[variable]
            lines.append(f"    {key}: [")
            for power in range(max(powers) + 1 if powers else 0):
                flat = ", ".join(number(v) for term in powers.get(power, []) for v in term)
                lines.append(f"      [{flat}],")
            lines.append("    ],")
        lines.append("  },")
    lines += ["};", ""]
    OUTPUT.write_text("\n".join(lines))
    print(f"wrote {OUTPUT.relative_to(REPO_ROOT)} ({OUTPUT.stat().st_size / 1024:.0f} KB)")
    assert math.isfinite(OUTPUT.stat().st_size)


if __name__ == "__main__":
    main()
