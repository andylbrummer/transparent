#!/usr/bin/env python3
"""
Reference values for the ephemeris tests, from JPL Horizons.

Writes packages/core/src/astro/ephemeris.fixture.ts: what Horizons (DE441)
gives for the Sun, the Moon and the planets at instants spread over
1900-2100 - astrometric place, distance, magnitude, illuminated fraction,
phase angle, the disc's orientation - seen from the Earth's centre, and for
the Sun and Moon also from the app's test site (Austin, 30.27 N 97.74 W).
packages/core/src/astro/ephemeris.test.ts holds the ephemeris to them.

Horizons is keyless: https://ssd.jpl.nasa.gov/api/horizons.api
(Giorgini et al., JPL Solar System Dynamics). Responses are cached in
tools/pipeline/.cache/horizons/; delete them to fetch again.

Usage:
    python3 tools/pipeline/fetch_horizons_fixture.py
"""

import datetime
import json
import urllib.parse
from pathlib import Path

from fetch_cache import cached_fetch

API = "https://ssd.jpl.nasa.gov/api/horizons.api"

# Spread over two centuries; two on the app's reference day.
INSTANTS = [
    "1900-04-01T00:00:00Z",
    "1923-09-10T06:00:00Z",
    "1947-01-25T18:00:00Z",
    "1969-07-20T20:17:00Z",
    "1987-04-10T19:21:00Z",
    "2000-01-01T12:00:00Z",
    "2013-11-03T12:00:00Z",
    "2026-11-09T06:00:00Z",
    "2026-11-09T18:00:00Z",
    "2038-03-21T03:00:00Z",
    "2061-07-28T09:00:00Z",
    "2084-12-27T15:00:00Z",
    "2099-12-31T21:00:00Z",
]

BODIES = {
    "sun": "10",
    "moon": "301",
    "mercury": "199",
    "venus": "299",
    "mars": "499",
    "jupiter": "599",
    "saturn": "699",
    "uranus": "799",
    "neptune": "899",
}

SITE = {"lat": 30.27, "lon": -97.74}

# Horizons column header -> fixture field.
COLUMNS = {
    "R.A._(ICRF)": "ra",
    "DEC_(ICRF)": "dec",
    "Azi_(a-app)": "azimuth",
    "Elev_(a-app)": "elevation",
    "APmag": "magnitude",
    "Illu%": "illuminatedPercent",
    "Ang-diam": "angularDiameterArcsec",
    "ObsSub-LON": "subObserverLon",
    "ObsSub-LAT": "subObserverLat",
    "SN.ang": "subSolarAngle",
    "NP.ang": "northPoleAngle",
    "r": "sunDistanceAu",
    "delta": "distanceAu",
    "S-T-O": "phaseAngle",
    "TDB-UT": "tdbMinusUt",
}

REPO_ROOT = Path(__file__).resolve().parents[2]
OUTPUT = REPO_ROOT / "packages" / "core" / "src" / "astro" / "ephemeris.fixture.ts"


def julian_date(iso: str) -> float:
    moment = datetime.datetime.fromisoformat(iso.replace("Z", "+00:00"))
    return moment.timestamp() / 86400 + 2440587.5


def query(body: str, center: str, site: str | None, name: str) -> list[dict[str, float]]:
    params = {
        "format": "text",
        "COMMAND": f"'{body}'",
        "CENTER": f"'{center}'",
        "EPHEM_TYPE": "'OBSERVER'",
        "TLIST": " ".join(f"'{julian_date(iso):.6f}'" for iso in INSTANTS),
        "QUANTITIES": "'1,4,9,10,13,14,16,17,19,20,24,30'",
        "ANG_FORMAT": "'DEG'",
        "APPARENT": "'AIRLESS'",
        "CSV_FORMAT": "'YES'",
        "OBJ_DATA": "'NO'",
    }
    if site:
        params["COORD_TYPE"] = "'GEODETIC'"
        params["SITE_COORD"] = f"'{site}'"
    text = cached_fetch(f"{API}?{urllib.parse.urlencode(params)}", f"horizons/{name}.txt").read_text()
    lines = text.splitlines()
    start = lines.index("$$SOE")
    end = lines.index("$$EOE")
    header = [cell.strip() for cell in lines[start - 2].split(",")]
    rows = []
    for line in lines[start + 1 : end]:
        cells = [cell.strip() for cell in line.split(",")]
        row: dict[str, float] = {}
        for column, cell in zip(header, cells):
            if column not in COLUMNS:
                continue
            try:
                row[COLUMNS[column]] = float(cell)
            except ValueError:
                # "n.a.": Horizons has no such quantity for this body (the Sun's phase).
                continue
        rows.append(row)
    assert len(rows) == len(INSTANTS), f"{name}: {len(rows)} rows"
    return rows


def main() -> None:
    site = f"{SITE['lon']},{SITE['lat']},0"
    fixture = {
        "instants": INSTANTS,
        "site": SITE,
        "geocentric": {name: query(body, "500@399", None, f"{name}-geocentric") for name, body in BODIES.items()},
        "topocentric": {
            name: query(BODIES[name], "coord@399", site, f"{name}-topocentric") for name in ("sun", "moon")
        },
    }
    body = json.dumps(fixture, indent=1)
    OUTPUT.write_text(
        "/**\n"
        " * JPL Horizons (DE441) reference values. GENERATED by\n"
        " * tools/pipeline/fetch_horizons_fixture.py - do not edit.\n"
        " *\n"
        " * Rows follow `instants`. Angles in degrees: astrometric ICRF ra/dec,\n"
        " * airless apparent azimuth/elevation, position angles from the true\n"
        " * north of date. Distances in au. tdbMinusUt in seconds.\n"
        " */\n"
        f"export const HORIZONS = {body} as const;\n"
    )
    print(f"wrote {OUTPUT.relative_to(REPO_ROOT)} ({OUTPUT.stat().st_size / 1024:.0f} KB)")


if __name__ == "__main__":
    main()
