#!/usr/bin/env python3
"""
Reference values for the planets' discs, from JPL Horizons.

Writes packages/core/src/astro/planet-discs.fixture.ts: what Horizons
(DE441, IAU 2015 rotation models) gives for Mercury to Neptune seen from
the Earth's centre at instants spread over 1950-2050 - angular diameter,
illuminated fraction, the planetodetic points under the Earth and under
the Sun, the position angle and distance of the north pole on the disc,
and the pole's own right ascension and declination.
packages/core/src/astro/planet-discs.test.ts holds the app to them.

Horizons is keyless: https://ssd.jpl.nasa.gov/api/horizons.api
(Giorgini et al., JPL Solar System Dynamics). Responses are cached in
tools/pipeline/.cache/horizons/; delete them to fetch again.

Usage:
    python3 tools/pipeline/fetch_planet_disc_fixture.py
"""

import json
import urllib.parse
from pathlib import Path

from fetch_cache import cached_fetch
from fetch_horizons_fixture import API, julian_date

# A century around the present: Saturn's rings wide open (2017) and edge-on (2025),
# Venus a thin crescent (2023-08, 2025-03), Mars at a close opposition (2003, 2020).
INSTANTS = [
    "1950-01-15T00:00:00Z",
    "1962-06-30T12:00:00Z",
    "1975-11-02T03:00:00Z",
    "1988-09-22T05:00:00Z",
    "1995-05-22T06:00:00Z",
    "2003-08-27T10:00:00Z",
    "2009-09-04T00:00:00Z",
    "2017-10-16T18:00:00Z",
    "2020-10-13T23:00:00Z",
    "2023-08-10T12:00:00Z",
    "2025-03-23T12:00:00Z",
    "2026-11-10T06:00:00Z",
    "2026-11-10T07:00:00Z",
    "2032-12-25T21:00:00Z",
    "2041-04-01T08:00:00Z",
    "2049-12-31T23:00:00Z",
]

BODIES = {
    "mercury": "199",
    "venus": "299",
    "mars": "499",
    "jupiter": "599",
    "saturn": "699",
    "uranus": "799",
    "neptune": "899",
}

# Horizons column header -> fixture field.
COLUMNS = {
    "Illu%": "illuminatedPercent",
    "Ang-diam": "angularDiameterArcsec",
    "ObsSub-LON": "subObserverLon",
    "ObsSub-LAT": "subObserverLat",
    "SunSub-LON": "subSolarLon",
    "SunSub-LAT": "subSolarLat",
    "NP.ang": "northPoleAngle",
    "NP.dist": "northPoleDistanceArcsec",
    "delta": "distanceAu",
    "S-T-O": "phaseAngle",
    "N.Pole-RA": "poleRa",
    "N.Pole-DC": "poleDec",
}

REPO_ROOT = Path(__file__).resolve().parents[2]
OUTPUT = REPO_ROOT / "packages" / "core" / "src" / "astro" / "planet-discs.fixture.ts"


def query(body: str, name: str) -> tuple[list[dict[str, float]], str]:
    params = {
        "format": "text",
        "COMMAND": f"'{body}'",
        "CENTER": "'500@399'",
        "EPHEM_TYPE": "'OBSERVER'",
        "TLIST": " ".join(f"'{julian_date(iso):.6f}'" for iso in INSTANTS),
        "QUANTITIES": "'10,13,14,15,17,20,24,32'",
        "ANG_FORMAT": "'DEG'",
        "CSV_FORMAT": "'YES'",
        "OBJ_DATA": "'NO'",
    }
    text = cached_fetch(f"{API}?{urllib.parse.urlencode(params)}", f"horizons/{name}-disc.txt").read_text()
    lines = text.splitlines()
    start = lines.index("$$SOE")
    end = lines.index("$$EOE")
    header = [cell.strip() for cell in lines[start - 2].split(",")]
    missing = set(COLUMNS) - set(header)
    assert not missing, f"{name}: Horizons did not return {missing}"
    rows = []
    for line in lines[start + 1 : end]:
        cells = [cell.strip() for cell in line.split(",")]
        rows.append({COLUMNS[column]: float(cell) for column, cell in zip(header, cells) if column in COLUMNS})
    assert len(rows) == len(INSTANTS), f"{name}: {len(rows)} rows"
    # Horizons states which way it counts each body's longitude.
    flat = " ".join(text.split())
    if "Positive longitude is to the WEST for this target" in flat or "longitude is to the WEST for this target" in flat:
        sense = "west"
    else:
        assert "longitude is to the EAST for this target" in flat, f"{name}: no longitude sense stated"
        sense = "east"
    return rows, sense


def main() -> None:
    fixture: dict[str, object] = {"instants": INSTANTS, "longitudePositive": {}, "geocentric": {}}
    for name, body in BODIES.items():
        rows, sense = query(body, name)
        fixture["geocentric"][name] = rows  # type: ignore[index]
        fixture["longitudePositive"][name] = sense  # type: ignore[index]
    OUTPUT.write_text(
        "/**\n"
        " * JPL Horizons (DE441, IAU 2015 rotation models) reference values for the\n"
        " * planets' discs. GENERATED by tools/pipeline/fetch_planet_disc_fixture.py -\n"
        " * do not edit.\n"
        " *\n"
        " * Rows follow `instants`, seen from the Earth's centre. Degrees unless\n"
        " * named otherwise: planetodetic sub-observer and sub-solar points (longitude\n"
        " * counted as `longitudePositive` says), the north pole's position angle\n"
        " * from the true north of date and its distance from the disc's centre\n"
        " * (negative: on the far side), the pole's ICRF right ascension and\n"
        " * declination. Diameters are equatorial.\n"
        " */\n"
        f"export const PLANET_DISCS = {json.dumps(fixture, indent=1)} as const;\n"
    )
    print(f"wrote {OUTPUT.relative_to(REPO_ROOT)} ({OUTPUT.stat().st_size / 1024:.0f} KB)")


if __name__ == "__main__":
    main()
