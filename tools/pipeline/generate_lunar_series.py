#!/usr/bin/env python3
"""
Content pipeline for Transparent Earth: the lunar theory's periodic terms.

Writes packages/core/src/astro/lunar-series.ts: Tables 47.A and 47.B of
J. Meeus, "Astronomical Algorithms" (2nd ed., 1998, ch. 47) - the main
periodic terms of the ELP-2000/82 lunar theory (Chapront-Touze & Chapront
1983). Rather than retype 120 rows from the book, they are taken from the
transcription in Sonia Keys' "meeus" (MIT licence), whose own tests
reproduce the book's worked example; the ephemeris tests then hold the
result to JPL Horizons.

Usage:
    python3 tools/pipeline/generate_lunar_series.py

Raw downloads are cached in tools/pipeline/.cache/. Standard library only.
"""

import re
from pathlib import Path

from fetch_cache import cached_fetch

SOURCE_URL = "https://raw.githubusercontent.com/soniakeys/meeus/master/v3/moonposition/moonposition.go"

REPO_ROOT = Path(__file__).resolve().parents[2]
OUTPUT = REPO_ROOT / "packages" / "core" / "src" / "astro" / "lunar-series.ts"

ROW = re.compile(r"^\s*\{([-\d.,\s]+)\},\s*$")


def table(source: str, name: str, width: int) -> list[list[int]]:
    """The rows of the Go array literal `var <name> = [...]`."""
    body = source.split(f"var {name} = [...]", 1)[1]
    body = body[: body.index("\n}\n")]
    rows = []
    for line in body.splitlines():
        match = ROW.match(line)
        if match:
            row = [int(float(cell)) for cell in match.group(1).split(",")]
            assert len(row) == width, line
            rows.append(row)
    return rows


def main() -> None:
    source = cached_fetch(SOURCE_URL, "meeus-moonposition.go").read_text()
    longitude = table(source, "ta", 6)
    latitude = table(source, "tb", 5)
    assert len(longitude) == 60 and len(latitude) == 60, (len(longitude), len(latitude))
    lines = [
        "/**",
        " * Periodic terms of the Moon's longitude, distance and latitude. GENERATED by",
        " * tools/pipeline/generate_lunar_series.py from Meeus, Astronomical Algorithms,",
        " * Tables 47.A and 47.B (after ELP-2000/82) - do not edit.",
        " */",
        "",
        "/** Rows of D, M, M′, F multipliers, then Σl (1e-6 degree, sine) and Σr (metre, cosine). */",
        "export const LUNAR_LONGITUDE_DISTANCE_TERMS: readonly (readonly number[])[] = [",
        *[f"  [{', '.join(str(v) for v in row)}]," for row in longitude],
        "];",
        "",
        "/** Rows of D, M, M′, F multipliers, then Σb (1e-6 degree, sine). */",
        "export const LUNAR_LATITUDE_TERMS: readonly (readonly number[])[] = [",
        *[f"  [{', '.join(str(v) for v in row)}]," for row in latitude],
        "];",
        "",
    ]
    OUTPUT.write_text("\n".join(lines))
    print(f"wrote {OUTPUT.relative_to(REPO_ROOT)}: {len(longitude)} + {len(latitude)} terms")


if __name__ == "__main__":
    main()
