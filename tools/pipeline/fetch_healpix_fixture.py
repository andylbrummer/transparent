#!/usr/bin/env python3
"""
Reference values for the HEALPix maths, from healpy.

Writes packages/core/src/astro/healpix.fixture.ts: for pixels spread over
several orders of the nested scheme - polar caps, the equatorial belt, the
seams between them - the centre and the four corners (north, west, south,
east) as healpy gives them, the pixel that contains a set of directions,
and the pixels a few discs touch. packages/core/src/astro/healpix.test.ts
holds the app's own implementation to them.

healpy wraps the HEALPix C++ library (Gorski et al. 2005, ApJ 622:759;
Zonca et al. 2019, JOSS 4:1298).

Usage (needs healpy: tools/pipeline/.cache/venv):
    python3 tools/pipeline/fetch_healpix_fixture.py
"""

import json
from pathlib import Path

import healpy as hp
import numpy as np

REPO_ROOT = Path(__file__).resolve().parents[2]
OUTPUT = REPO_ROOT / "packages" / "core" / "src" / "astro" / "healpix.fixture.ts"

ORDERS = [0, 1, 3, 6, 9]
PIXELS_PER_ORDER = 14
# (ra, dec, radius) in degrees: the pole, the equator, the cap seam at |dec| = 41.8, a wide one.
DISCS = [(10.0, 89.0, 3.0), (83.8, -5.4, 2.0), (200.0, 41.8, 4.0), (310.0, -41.8, 1.0), (0.2, 0.1, 12.0), (266.4, -28.9, 0.3)]
DISC_ORDERS = [3, 5]


def r(values) -> list[float]:
    return [round(float(v), 12) for v in values]


def main() -> None:
    rng = np.random.default_rng(20261110)
    pixels = []
    for order in ORDERS:
        nside = 2**order
        npix = 12 * nside * nside
        chosen = sorted(set([0, npix - 1] + [int(v) for v in rng.integers(0, npix, PIXELS_PER_ORDER)])) if npix > PIXELS_PER_ORDER else list(range(npix))
        for ipix in chosen:
            corners = hp.boundaries(nside, ipix, step=1, nest=True)  # columns: N, W, S, E
            pixels.append(
                {
                    "order": order,
                    "ipix": ipix,
                    "centre": r(hp.pix2vec(nside, ipix, nest=True)),
                    "north": r(corners[:, 0]),
                    "west": r(corners[:, 1]),
                    "south": r(corners[:, 2]),
                    "east": r(corners[:, 3]),
                }
            )
    directions = []
    for _ in range(40):
        v = rng.normal(size=3)
        v /= np.linalg.norm(v)
        directions.append({"direction": r(v), "pixels": {str(order): int(hp.vec2pix(2**order, *v, nest=True)) for order in ORDERS}})
    discs = []
    for ra, dec, radius in DISCS:
        v = hp.ang2vec(ra, dec, lonlat=True)
        for order in DISC_ORDERS:
            # inclusive: every pixel that overlaps the disc (and, by healpy's design, a few that only come near).
            inclusive = hp.query_disc(2**order, v, np.radians(radius), inclusive=True, fact=64, nest=True)
            centres_inside = hp.query_disc(2**order, v, np.radians(radius), inclusive=False, nest=True)
            discs.append(
                {
                    "direction": r(v),
                    "radiusDeg": radius,
                    "order": order,
                    "overlapping": sorted(int(p) for p in inclusive),
                    "centresInside": sorted(int(p) for p in centres_inside),
                }
            )
    fixture = {"pixels": pixels, "directions": directions, "discs": discs}
    OUTPUT.write_text(
        "/**\n"
        " * HEALPix reference values from healpy (nested scheme). GENERATED by\n"
        " * tools/pipeline/fetch_healpix_fixture.py - do not edit.\n"
        " *\n"
        " * `pixels`: centre and corners as unit vectors (z the pole, x toward\n"
        " * longitude 0). `directions`: the pixel holding each direction, by order.\n"
        " * `discs`: pixels whose centre is inside the disc, and healpy's inclusive\n"
        " * list (every overlapping pixel, plus a few near misses).\n"
        " */\n"
        f"export const HEALPIX = {json.dumps(fixture)} as const;\n"
    )
    print(f"wrote {OUTPUT.relative_to(REPO_ROOT)} ({OUTPUT.stat().st_size / 1024:.0f} KB), {len(pixels)} pixels")


if __name__ == "__main__":
    main()
