/**
 * Writes docs/DATA-SOURCES.md: one index of every dataset the app shows,
 * with its licence, built from the same credits the app lists in its
 * panel - so the document cannot drift from what ships.
 *
 *   npm run docs:sources            # rewrite the index
 *   npm run docs:sources -- --check # exit 1 if the file is out of date
 */

import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { LAYER_DEFINITIONS } from '../src/layers/registry';
import { LAYER_SECTIONS, type Credit } from '../src/layers/types';
import { BUILTIN_CREDITS } from '../src/ui/credits';

const DOCS = fileURLToPath(new URL('../../docs/', import.meta.url));
const OUTPUT = `${DOCS}DATA-SOURCES.md`;

/** Licence wording that restricts reuse beyond attribution; such sources get their own list. */
const RESTRICTIVE = /share-?alike|BY-SA|BY-NC|ODbL|GPL|non-commercial|scientific purposes|no stated licence|personal|copyright of/i;

const cell = (text: string): string => text.replace(/\|/g, '\\|').replace(/\s+/g, ' ').trim();
const link = (credit: Credit): string => `[${cell(credit.source)}](${credit.url})`;

export function renderIndex(): string {
  const lines: string[] = [
    '# Data sources',
    '',
    '<!-- Generated by app/scripts/data-sources.ts (npm run docs:sources). Do not edit by hand. -->',
    '',
    'Every dataset Transparent Earth shows, who made it and under what terms. This index is generated from',
    'the credits each layer declares, which are also what the app lists under **Layers → Data credits**.',
    'The per-slice documents listed at the end add full citations, how each file is baked or fetched, and what was',
    'checked against what.',
    '',
    'All sources are free and keyless. Static data is baked by the scripts in `tools/pipeline/` into `app/public/`;',
    'live data is fetched by the browser from the provider, with a baked snapshot as fallback.',
    '',
  ];

  // One row per source, however many layers draw from it.
  const restricted = new Map<string, { credit: Credit; layers: string[] }>();
  const note = (where: string, credit: Credit): void => {
    if (!RESTRICTIVE.test(credit.licence)) return;
    const key = `${credit.source}|${credit.licence}`;
    const entry = restricted.get(key) ?? { credit, layers: [] };
    if (!entry.layers.includes(where)) entry.layers.push(where);
    restricted.set(key, entry);
  };

  const body: string[] = [];
  body.push('## Always loaded', '', '| What | Source | Licence |', '| --- | --- | --- |');
  for (const credit of BUILTIN_CREDITS) {
    body.push(`| ${cell(credit.what)} | ${link(credit)} | ${cell(credit.licence)} |`);
    note('always loaded', credit);
  }
  body.push('');

  for (const section of LAYER_SECTIONS) {
    const layers = LAYER_DEFINITIONS.filter((d) => d.section === section);
    if (layers.length === 0) continue;
    body.push(`## ${section}`, '', '| Layer | Default | What | Source | Licence |', '| --- | --- | --- | --- | --- |');
    for (const layer of layers) {
      const name = `${cell(layer.label)} (\`${layer.id}\`)`;
      const onOff = layer.defaultOn ? 'on' : 'off';
      if (layer.credits.length === 0) {
        body.push(`| ${name} | ${onOff} | computed in the app; no outside data | | |`);
        continue;
      }
      layer.credits.forEach((credit, index) => {
        body.push(`| ${index === 0 ? name : ''} | ${index === 0 ? onOff : ''} | ${cell(credit.what)} | ${link(credit)} | ${cell(credit.licence)} |`);
        note(layer.label, credit);
      });
    }
    body.push('');
  }

  lines.push(
    '## Sources whose terms go beyond attribution',
    '',
    'Share-alike, non-commercial, or without a stated licence. Each is credited in the app; each sits in its own',
    'files and can be removed without touching other layers.',
    '',
    '| Layers | What | Source | Licence as declared |',
    '| --- | --- | --- | --- |',
    ...[...restricted.values()].map(
      ({ credit, layers }) => `| ${cell(layers.join('; '))} | ${cell(credit.what)} | ${link(credit)} | ${cell(credit.licence)} |`
    ),
    '',
    ...body
  );

  const perSlice = existsSync(`${DOCS}data-sources`) ? readdirSync(`${DOCS}data-sources`).filter((f) => f.endsWith('.md')).sort() : [];
  lines.push('## Per-slice documents', '');
  for (const file of perSlice) {
    const title = readFileSync(`${DOCS}data-sources/${file}`, 'utf8').split('\n')[0].replace(/^#\s*/, '');
    lines.push(`- [${title}](data-sources/${file})`);
  }
  lines.push('', 'See also `app/public/geo/ATTRIBUTION.md` (the baked map files) and `tools/pipeline/README.md` (how to re-bake).', '');
  return lines.join('\n');
}

const text = renderIndex();
if (process.argv.includes('--check')) {
  const current = existsSync(OUTPUT) ? readFileSync(OUTPUT, 'utf8') : '';
  if (current !== text) {
    console.error('docs/DATA-SOURCES.md is out of date: run `npm run docs:sources`');
    process.exit(1);
  }
} else {
  writeFileSync(OUTPUT, text);
  console.error(`wrote ${OUTPUT}: ${LAYER_DEFINITIONS.length} layers`);
}
