/**
 * Seismic catalogue client and playback clock.
 * Pure functions — no browser APIs (IDB, fetch) here.
 *
 * The catalogue is the USGS ANSS Comprehensive Catalog (ComCat). Both its
 * FDSN event service and its real-time feeds answer with the same GeoJSON:
 * a FeatureCollection whose features carry `properties.time` in epoch
 * milliseconds, `properties.mag`, and `geometry.coordinates` as
 * [longitude, latitude, depth], depth in kilometres, positive down.
 */

/** FDSN event query endpoint (historical searches). */
export const USGS_FDSN_EVENT_URL = 'https://earthquake.usgs.gov/fdsnws/event/1/query';

/** The service refuses (HTTP 400) any query matching more events than this; page with limit/offset. */
export const USGS_FDSN_MAX_EVENTS = 20000;

type FeedThreshold = 'significant' | '4.5' | '2.5' | '1.0' | 'all';
type FeedPeriod = 'hour' | 'day' | 'week' | 'month';

/** Real-time summary feeds, regenerated by USGS every minute. */
export type UsgsFeedName = `${FeedThreshold}_${FeedPeriod}`;

export function usgsFeedUrl(feed: UsgsFeedName): string {
  return `https://earthquake.usgs.gov/earthquakes/feed/v1.0/summary/${feed}.geojson`;
}

export interface EventRecord {
  readonly id: string;
  readonly time: string;     // ISO 8601
  readonly lat: number;
  readonly lon: number;
  /** Kilometres below sea level; slightly negative for an event inside a mountain. */
  readonly depthKm: number;
  readonly mag: number;
  readonly name: string;
  /** How the magnitude was measured: 'mww', 'mb', 'ml', … */
  readonly magType?: string;
  /** ComCat's event type: 'earthquake', 'quarry blast', 'nuclear explosion', … */
  readonly eventType?: string;
}

export interface CatalogQuery {
  readonly startTime: string;
  readonly endTime: string;
  readonly minMagnitude?: number;
  readonly maxMagnitude?: number;
  readonly minLatitude?: number;
  readonly maxLatitude?: number;
  readonly minLongitude?: number;
  readonly maxLongitude?: number;
  /** ComCat lists explosions, quarry blasts and collapses too; 'earthquake' leaves them out. */
  readonly eventType?: string;
  readonly orderBy?: 'time' | 'time-asc' | 'magnitude' | 'magnitude-asc';
  /** Page size, at most USGS_FDSN_MAX_EVENTS. */
  readonly limit?: number;
  /** First event of the page, counted from 1 as FDSN does. */
  readonly offset?: number;
}

/**
 * Build USGS FDSN GeoJSON query URL from a CatalogQuery.
 */
export function buildQueryUrl(baseUrl: string, query: CatalogQuery): string {
  const params = new URLSearchParams({
    format: 'geojson',
    starttime: query.startTime,
    endtime: query.endTime,
  });

  if (query.minMagnitude !== undefined) params.set('minmagnitude', String(query.minMagnitude));
  if (query.maxMagnitude !== undefined) params.set('maxmagnitude', String(query.maxMagnitude));
  if (query.minLatitude !== undefined) params.set('minlatitude', String(query.minLatitude));
  if (query.maxLatitude !== undefined) params.set('maxlatitude', String(query.maxLatitude));
  if (query.minLongitude !== undefined) params.set('minlongitude', String(query.minLongitude));
  if (query.maxLongitude !== undefined) params.set('maxlongitude', String(query.maxLongitude));
  if (query.eventType !== undefined) params.set('eventtype', query.eventType);
  if (query.orderBy !== undefined) params.set('orderby', query.orderBy);
  if (query.limit !== undefined) params.set('limit', String(query.limit));
  if (query.offset !== undefined) params.set('offset', String(query.offset));

  return `${baseUrl}?${params.toString()}`;
}

/** Dates a JavaScript Date can hold: ±8.64e15 ms around the epoch. */
const MAX_DATE_MS = 8.64e15;

/**
 * Normalize a USGS GeoJSON feature into an EventRecord.
 *
 * Returns null unless every field that positions the event is genuinely
 * present. A substituted coordinate or magnitude would render a phantom
 * quake at 0°N 0°E rather than surfacing the bad record, so missing data
 * rejects the feature outright.
 *
 * `place` is the one exception: it is a display label, not geometry, so a
 * missing one falls back without discarding an otherwise valid event.
 */
export function normalizeEvent(feature: unknown): EventRecord | null {
  if (typeof feature !== 'object' || feature === null) return null;

  const f = feature as Record<string, unknown>;
  const props = (f.properties ?? {}) as Record<string, unknown>;
  const geom = (f.geometry ?? {}) as Record<string, unknown>;
  const coords = Array.isArray(geom.coordinates) ? (geom.coordinates as unknown[]) : [];

  // A ComCat id is the network code followed by the network's own event
  // code ('us' + '7000abcd'); the code alone is not unique across networks.
  const rawId = isNonEmptyString(f.id)
    ? f.id
    : isNonEmptyString(props.net) && isNonEmptyString(props.code)
      ? props.net + props.code
      : null;
  if (rawId === null) return null;

  // USGS reports origin time as epoch milliseconds.
  const timeMs = toFiniteNumber(props.time);
  if (timeMs === null || Math.abs(timeMs) > MAX_DATE_MS) return null;

  const lon = toFiniteNumber(coords[0]);
  const lat = toFiniteNumber(coords[1]);
  const depth = toFiniteNumber(coords[2]);
  const mag = toFiniteNumber(props.mag);

  if (lon === null || lat === null || depth === null || mag === null) return null;
  if (lat < -90 || lat > 90 || lon < -180 || lon > 180) return null;

  return {
    id: rawId,
    time: new Date(timeMs).toISOString(),
    lat,
    lon,
    depthKm: depth, // USGS reports depth in kilometres
    mag,
    name: isNonEmptyString(props.place) ? props.place : 'Unknown location',
    ...(isNonEmptyString(props.magType) ? { magType: props.magType } : {}),
    ...(isNonEmptyString(props.type) ? { eventType: props.type } : {}),
  };
}

function isNonEmptyString(value: unknown): value is string {
  return typeof value === 'string' && value !== '';
}

/** Numbers and numeric strings; never the booleans, arrays and blanks that Number() would coerce. */
function toFiniteNumber(value: unknown): number | null {
  const n = typeof value === 'string' && value.trim() !== '' ? Number(value) : value;
  return typeof n === 'number' && Number.isFinite(n) ? n : null;
}

export interface EventCollection {
  /** When USGS built the response (metadata.generated), epoch ms; null if absent. */
  readonly generatedMs: number | null;
  /** Usable events, oldest first. */
  readonly events: readonly EventRecord[];
  /** Features left out: unusable, or not of a wanted type. */
  readonly rejected: number;
}

export interface ParseOptions {
  /**
   * Keep only these ComCat event types. Default: ['earthquake'], because
   * the catalogue and the feeds also carry quarry blasts, explosions,
   * collapses and the like. Pass null to keep everything.
   */
  readonly eventTypes?: readonly string[] | null;
}

/**
 * Parse a USGS GeoJSON FeatureCollection - an FDSN query response or a
 * real-time feed. Throws if it is not one, so a proxy's error page is not
 * mistaken for "no earthquakes".
 */
export function parseEventCollection(json: unknown, options: ParseOptions = {}): EventCollection {
  const root = (typeof json === 'object' && json !== null ? json : {}) as Record<string, unknown>;
  if (root.type !== 'FeatureCollection' || !Array.isArray(root.features)) {
    throw new Error('not a USGS GeoJSON FeatureCollection');
  }
  const features = root.features as unknown[];
  const wanted = options.eventTypes === undefined ? ['earthquake'] : options.eventTypes;
  const metadata = (root.metadata ?? {}) as Record<string, unknown>;
  const events: EventRecord[] = [];
  for (const feature of features) {
    const event = normalizeEvent(feature);
    if (event === null) continue;
    if (wanted !== null && (event.eventType === undefined || !wanted.includes(event.eventType))) continue;
    events.push(event);
  }
  events.sort((a, b) => Date.parse(a.time) - Date.parse(b.time));
  return {
    generatedMs: toFiniteNumber(metadata.generated),
    events,
    rejected: features.length - events.length,
  };
}

/**
 * Merge event lists into one, oldest first. An id seen twice keeps its
 * last occurrence, so pass the fresher list last: ComCat revises an
 * event's location and magnitude under the same id.
 */
export function mergeEvents(...lists: readonly (readonly EventRecord[])[]): EventRecord[] {
  const byId = new Map<string, EventRecord>();
  for (const list of lists) for (const event of list) byId.set(event.id, event);
  return [...byId.values()].sort((a, b) => Date.parse(a.time) - Date.parse(b.time));
}

/**
 * Playback clock: maps wall time to simulation time.
 */
export interface ClockState {
  readonly running: boolean;
  readonly wallTimeMs: number;      // current wall timestamp
  readonly simTimeMs: number;       // current simulation timestamp
  readonly compression: number;     // sim seconds per wall second (1 = real-time)
  /** Everything loaded, oldest first. Seeking back brings earlier events into play again. */
  readonly events: readonly EventRecord[];
  /** The events whose waves are in flight at simTimeMs: at most MAX_ACTIVE_EVENTS, the latest. */
  readonly activeEvents: readonly EventRecord[];
}

/** Wavefront budget (spec/seismic.md): oldest culled first. */
export const MAX_ACTIVE_EVENTS = 8;
/** An event stays active this long after its origin: by then its waves have long since crossed the Earth. */
export const ACTIVE_WINDOW_MS = 86400000;

export const DEFAULT_CLOCK: ClockState = {
  running: false,
  wallTimeMs: 0,
  simTimeMs: 0,
  compression: 60, // 1s wall = 1min sim
  events: [],
  activeEvents: [],
};

/**
 * The events in flight at a simulation time: already happened, and no
 * more than ACTIVE_WINDOW_MS ago. `events` must be sorted oldest first.
 */
export function activeEventsAt(events: readonly EventRecord[], simTimeMs: number): readonly EventRecord[] {
  return events
    .filter((e) => {
      const t0 = Date.parse(e.time);
      return t0 <= simTimeMs && t0 >= simTimeMs - ACTIVE_WINDOW_MS;
    })
    .slice(-MAX_ACTIVE_EVENTS);
}

/**
 * Advance the clock by a wall-time delta.
 */
export function tickClock(state: ClockState, deltaWallMs: number): ClockState {
  if (!state.running) return state;

  const newSimTime = state.simTimeMs + deltaWallMs * state.compression;
  return {
    ...state,
    wallTimeMs: state.wallTimeMs + deltaWallMs,
    simTimeMs: newSimTime,
    activeEvents: activeEventsAt(state.events, newSimTime),
  };
}

/**
 * Seek the clock to a specific simulation time.
 */
export function seekClock(state: ClockState, targetSimTimeMs: number): ClockState {
  return {
    ...state,
    simTimeMs: targetSimTimeMs,
    activeEvents: activeEventsAt(state.events, targetSimTimeMs),
  };
}

/**
 * Set the compression ratio.
 * Preserves the current simulation time position.
 */
export function setCompression(state: ClockState, compression: number): ClockState {
  return {
    ...state,
    compression: Math.max(1, compression),
  };
}

/**
 * Toggle play/pause.
 */
export function togglePlay(state: ClockState): ClockState {
  return { ...state, running: !state.running };
}

/**
 * Load a catalogue into the clock. Which of its events are active follows
 * from the simulation time, here and on every tick and seek.
 */
export function loadEvents(state: ClockState, events: readonly EventRecord[]): ClockState {
  const sorted = [...events].sort((a, b) => Date.parse(a.time) - Date.parse(b.time));
  return {
    ...state,
    events: sorted,
    activeEvents: activeEventsAt(sorted, state.simTimeMs),
  };
}
